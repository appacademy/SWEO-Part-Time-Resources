//Difference between EM and REM

//EM - Relative unit of measurement, specifically relative to the element its contained within
// Element measurement

/* 
h1 {
    font-size: 10px;
    padding: 1em
}

div {
    font-size: 50px;
    padding: 1em;
}
1em is 100% of the font-size of THIS ELEMENT so the padding is 10px;
*/

//REM - Is also a relative unit of measurement BUT its relative to the body font size

/*

body {
    font-size: 12px;
}

h1 {
    padding: 2rem;
}

*/

